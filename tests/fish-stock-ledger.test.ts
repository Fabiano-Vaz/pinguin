const assert = require("node:assert/strict");
const { FishStockLedger, FISH_LIFETIME_MS, parseFishStock } = require("../src/runtime/fish-stock-ledger.ts");
let now = 1000000;
const clock = () => now;
let stock = new FishStockLedger(null, 5, clock);
const initialExpiry = now + FISH_LIFETIME_MS;
assert.equal(stock.balance, 5);
stock.add(2);
assert.equal(stock.snapshot.batches.length, 1, "Awards at the same time share a batch");
now += 3600000;
stock.add(10);
const saved = stock.snapshot;
saved.batches[0].amount = 999;
assert.equal(stock.balance, 17, "Snapshots cannot mutate live balances");
assert.equal(stock.spend(8), true);
assert.deepEqual(stock.snapshot.batches, [{ amount: 9, expiresAt: initialExpiry + 3600000 }]);
assert.equal(stock.spend(10), false);
assert.equal(stock.balance, 9);
stock = new FishStockLedger(stock.snapshot, 5, clock);
now = initialExpiry + 3600000 - 1;
assert.equal(stock.balance, 9, "All 24 hours remain available");
now += 1;
assert.equal(stock.spend(1), false, "Expired fish cannot be spent");
assert.equal(stock.balance, 0);
assert.equal(new FishStockLedger(stock.snapshot, 5, clock).balance, 0);
assert.equal(new FishStockLedger({ version: 1, batches: [{ amount: 4, expiresAt: now - 1 }] }, 5, clock).balance, 0);
for (const amount of [-1, 0, NaN, Infinity, 1.5]) {
  assert.equal(stock.add(amount), false);
  assert.equal(stock.spend(amount), false);
}
assert.equal(parseFishStock({ version: 2, batches: [] }), undefined);
assert.deepEqual(parseFishStock({ version: 1, batches: [null, {}, { amount: -1, expiresAt: now }, { amount: 2, expiresAt: Infinity }] }), { version: 1, batches: [] });
stock.add(3);
now += 3600000;
stock.add(4);
const first = stock.snapshot.batches[0].expiresAt;
stock = new FishStockLedger(stock.snapshot, 5, clock);
now = first;
assert.equal(stock.expire(), 3);
assert.equal(stock.balance, 4, "Each award has its own expiration");
assert.equal(stock.nextExpiration, first + 3600000);
console.log("fish stock ledger tests passed");
